# The health tab's on-model masks (KnoxHealthModel.lua): one hidden, texture-only
# clothing item per body part and gender, painted on the 3D model copy's skin like
# the game's own bandage and wound items, coloured by its tint. The masks are the
# author's own from Grid Character Hub (tools\doll\build_highlights.ps1 there,
# UvMaskBuilder.cs: the game's MaleBody / FemaleBody UV split by bone weights),
# taken over under Knox's names so both mods can be on together:
#   textures/KnoxHealth/hl_<m|f>_<Part>.png           the mask (white, tinted in game)
#   clothing/clothingItems/KH_HL_<M|F>_<Part>.xml     clothingItem: no model, the mask, tintable
#   fileGuidTable.xml                                  registers them (stable GUIDs from the name)
#   scripts/knox_health_masks.txt                      items KnoxHealth.KH_HL_<M|F>_<Part>
#
# Usage: powershell -ExecutionPolicy Bypass -File tools\import_health_masks.ps1 [-From <GCH 42\media>]

param([string]$From = "C:\Users\pielo\Zomboid\mods\GridInventoryMedical\42\media")

$ErrorActionPreference = "Stop"
$root = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
$media = Join-Path $root "42\media"
$texDir = Join-Path $media "textures\KnoxHealth"
$xmlDir = Join-Path $media "clothing\clothingItems"
$scrDir = Join-Path $media "scripts"
New-Item -ItemType Directory -Force $texDir, $xmlDir, $scrDir | Out-Null

$parts = "Hand_L", "Hand_R", "ForeArm_L", "ForeArm_R", "UpperArm_L", "UpperArm_R", "Torso_Upper", "Torso_Lower",
         "Head", "Neck", "Groin", "UpperLeg_L", "UpperLeg_R", "LowerLeg_L", "LowerLeg_R", "Foot_L", "Foot_R"

$md5 = [System.Security.Cryptography.MD5]::Create()
function StableGuid([string]$name) {
    $h = $md5.ComputeHash([Text.Encoding]::UTF8.GetBytes("KnoxHealth:" + $name))
    return (New-Object Guid (,$h)).ToString()
}

$utf8 = New-Object Text.UTF8Encoding $false
$guids = New-Object Text.StringBuilder
$items = New-Object Text.StringBuilder
$n = 0
foreach ($g in "m", "f") {
    foreach ($p in $parts) {
        $src = Join-Path $From ("textures\HealthInventory\hl_{0}_{1}.png" -f $g, $p)
        if (-not (Test-Path $src)) { throw "missing mask: $src" }
        Copy-Item $src (Join-Path $texDir ("hl_{0}_{1}.png" -f $g, $p)) -Force
        $id = "KH_HL_{0}_{1}" -f $g.ToUpper(), $p
        $guid = StableGuid $id
        $xml = @"
<?xml version="1.0" encoding="utf-8"?>
<clothingItem>
	<m_MaleModel></m_MaleModel>
	<m_FemaleModel></m_FemaleModel>
	<m_GUID>$guid</m_GUID>
	<m_Static>false</m_Static>
	<m_AllowRandomHue>false</m_AllowRandomHue>
	<m_AllowRandomTint>true</m_AllowRandomTint>
	<m_AttachBone></m_AttachBone>
	<m_BaseTextures>KnoxHealth\hl_$($g)_$p</m_BaseTextures>
</clothingItem>
"@
        [IO.File]::WriteAllText((Join-Path $xmlDir "$id.xml"), $xml.Replace("`r`n", "`n").Replace("`n", "`r`n"), $utf8)
        [void]$guids.Append("`t<files>`r`n`t`t<path>media/clothing/clothingItems/$id.xml</path>`r`n`t`t<guid>$guid</guid>`r`n`t</files>`r`n")
        [void]$items.Append("`r`n    item $id`r`n    {`r`n        DisplayCategory = Bandage,`r`n        ItemType = base:clothing,`r`n        Weight = 0.0,`r`n        BodyLocation = base:bandage,`r`n        ClothingItem = $id,`r`n        WorldRender = false,`r`n        hidden = true,`r`n    }`r`n")
        $n++
    }
}
# the 3D skeleton (Knox Inventory Java/tools/healthpaint/SkeletonGen.java) - kept in the table
[void]$guids.Append("`t<files>`r`n`t`t<path>media/clothing/clothingItems/KH_Skeleton.xml</path>`r`n`t`t<guid>4b6e0d2a-7c51-4f0e-9a3d-6b1c2e8f5a71</guid>`r`n`t</files>`r`n")
[IO.File]::WriteAllText((Join-Path $media "fileGuidTable.xml"),
    "<?xml version=`"1.0`" encoding=`"utf-8`"?>`r`n<fileGuidTable>`r`n" + $guids.ToString() + "</fileGuidTable>`r`n", $utf8)
[IO.File]::WriteAllText((Join-Path $scrDir "knox_health_masks.txt"),
    "/* GENERATED by tools/import_health_masks.ps1 - do not edit by hand.`r`n   Hidden mask items worn by the health tab's 3D model copy only (KnoxHealthModel.lua). */`r`nmodule KnoxHealth`r`n{`r`n    imports`r`n    {`r`n        Base`r`n    }`r`n" + $items.ToString() + "}`r`n", $utf8)
Write-Host "$n masks imported into $media"
