-- Item inspection window ("Inspect" in an item's context menu), like the
-- mockup: the item's 3D model turning slowly on top (drag with the left
-- button to turn it yourself, Shift+drag to roll, wheel to zoom), name,
-- stats and description below. A child of the Knox screen.
--
-- The model is drawn by the game's UI3DScene (the one its debug editors use):
-- the item's world / static / weapon model script, seen by a camera that
-- turns around it. Items without a 3D model show their icon, large.

require "ISUI/ISPanel"
require "Vehicles/ISUI/ISUI3DScene"
require "ISUI/ISInventoryItem"
require "Knox/KnoxTheme"
require "Knox/KnoxWindowDrag"
require "Knox/KnoxThread"

local T = KnoxTheme
local SPIN_DEG_PER_S = 22
local SPIN_RESUME_MS = 2000

-- 3D view ---------------------------------------------------------------------------

KnoxInspectScene = ISUI3DScene:derive("KnoxInspectScene")

function KnoxInspectScene:new(x, y, w, h, window)
    local o = ISUI3DScene.new(self, x, y, w, h)
    o.background = false
    o.window = window
    o.rx, o.ry, o.rz = 20, 30, 0
    o.zoom = 14
    o.lastMs = getTimestampMs()
    o.touchMs = 0
    -- own scene object id per window (the Java part keys item colors by it)
    KnoxInspectScene.count = (KnoxInspectScene.count or 0) + 1
    o.objId = "knox_item_" .. KnoxInspectScene.count
    return o
end

--- The item's color as the game paints it: a clothing item's tint and hue
--- (random per item), else an item's custom color; nil for plain items.
local function tintOf(item)
    local ci = item.getClothingItem and item:getClothingItem()
    local v = item.getVisual and item:getVisual()
    if ci and v then
        local c = v:getTint(ci)
        local hue = v:getHue(ci) or 0
        if c then return c:getRedFloat(), c:getGreenFloat(), c:getBlueFloat(), hue end
    end
    if item:isCustomColor() then
        return item:getColorRed(), item:getColorGreen(), item:getColorBlue(), 0
    end
    return nil
end

--- Which texture choice of its clothing item an item shows (0 = first).
local function textureChoiceOf(item)
    local v = item.getVisual and item:getVisual()
    if not v then return 0 end
    local i = v.getTextureChoice and v:getTextureChoice() or -1
    if i == nil or i < 0 then i = v.getBaseTexture and v:getBaseTexture() or 0 end
    if i == nil or i < 0 then i = 0 end
    return i
end

--- Model script of an item: world model, else static model, else weapon model.
--- Bags and clothes have world models without a texture of their own (in the
--- world it comes from the clothing item, which this scene can't apply): for
--- them we use the textured copies in module KnoxInspect, generated by
--- tools/gen_inspect_models.py - one per texture choice. No model: the icon.
function KnoxInspectScene.modelFor(item)
    local names = {}
    local function add(n) if n and n ~= "" then table.insert(names, n) end end
    add(item:getWorldStaticModel())
    add(item:getStaticModel())
    if instanceof(item, "HandWeapon") then add(item:getWeaponSprite()) end
    local sm = getScriptManager()
    for _, n in ipairs(names) do
        local ms = sm:getModelScript(n)
        if not ms and not string.find(n, "%.") then ms = sm:getModelScript("Base." .. n) end
        if ms then
            -- a textured copy exists only for clothing-textured models: always
            -- prefer it (getTextureName() isn't empty for them, it can't tell)
            -- copies are per clothing item (one world model can serve several
            -- items with different textures): <WorldModel>__<ClothingItem>_<choice>
            local clothing = item.getClothingItemName and item:getClothingItemName()
            if clothing and clothing ~= "" then
                local prefix = "KnoxInspect." .. ms:getName() .. "__" .. clothing .. "_"
                local copy = sm:getModelScript(prefix .. textureChoiceOf(item))
                    or sm:getModelScript(prefix .. "0")
                if copy then return copy:getFullType() end
            end
            return ms:getFullType()
        end
    end
    return nil
end

-- Framing: the Java part's knoxModelBounds() gives the model's box in the
-- scene object's space. The model is centered on the scene's origin (which
-- the view turns around) and scaled so its diagonal takes FIT_FILL of the view
-- at zoom FIT_ZOOM. The scene is orthographic: visible height =
-- H * 1366 / W / zoomMult, zoomMult = e^(0.2 zoom) * 160 / 1.82
-- (UI3DScene.calcMatrices / zoomMult).
local FIT_ZOOM = 10
local FIT_FILL = 0.85
local START_PITCH = 20

local function zoomMult(z)
    return math.exp(0.2 * z) * 160 / 1.82
end

--- Center and scale the model from its exact bounds. False while they are
--- not known yet (the model is still loading): try again next frame.
function KnoxInspectScene:fit()
    local s = knoxModelBounds(self.model)
    if not s then return false end
    local v = {}
    for n in string.gmatch(s, "[^,]+") do table.insert(v, tonumber(n)) end
    if #v < 6 then return false end
    local cx, cy, cz = (v[1] + v[4]) / 2, (v[2] + v[5]) / 2, (v[3] + v[6]) / 2
    local dx, dy, dz = v[4] - v[1], v[5] - v[2], v[6] - v[3]
    local diag = math.sqrt(dx * dx + dy * dy + dz * dz)
    if diag <= 0 then return false end
    local W, H = self:getWidth(), self:getHeight()
    local visibleH = H * 1366 / W / zoomMult(FIT_ZOOM)
    local visibleW = 1366 / zoomMult(FIT_ZOOM)
    local k = FIT_FILL * math.min(visibleH, visibleW) / diag
    local j = self.javaObject
    j:fromLua1("getObjectScale", self.objId):set(k, k, k)
    j:fromLua1("getObjectTranslation", self.objId):set(-k * cx, -k * cy, -k * cz)
    return true
end

function KnoxInspectScene:setup(item)
    local j = self.javaObject
    self:setView("UserDefined")
    j:fromLua1("setMaxZoom", 30)
    j:fromLua1("setDrawGrid", false)
    j:fromLua1("setDrawGridAxes", false)
    j:fromLua1("setDrawGridPlane", false)
    j:fromLua1("setGizmoVisible", "none")
    self.model = KnoxInspectScene.modelFor(item)
    if self.model then
        j:fromLua2("createModel", self.objId, self.model)
        j:fromLua2("setModelUseWorldAttachment", self.objId, false)
        -- the item's own color (clothes' tint), applied by the Java part
        local r, g, b, hue = tintOf(item)
        if r then knoxSceneTint(j, r, g, b, hue) end
        self.fitted = self:fit()
    end
    self.baseZoom = FIT_ZOOM
    self:resetView()
end

--- Starting view: whole model in frame, centered (see fit), the user's
--- panning undone.
function KnoxInspectScene:resetView()
    self.rx, self.ry, self.rz = START_PITCH, 30, 0
    self.zoom = self.baseZoom
    self:applyView()
    if (self.panX or 0) ~= 0 or (self.panY or 0) ~= 0 then
        self.javaObject:fromLua2("dragView", -(self.panX or 0), -(self.panY or 0))
    end
    self.panX, self.panY = 0, 0
end

function KnoxInspectScene:applyView()
    local j = self.javaObject
    j:fromLua1("setZoom", self.zoom)
    j:fromLua3("setViewRotation", self.rx, self.ry, self.rz)
end

function KnoxInspectScene:prerender()
    local now = getTimestampMs()
    local dt = (now - self.lastMs) / 1000
    self.lastMs = now
    if self.dragging and not isMouseButtonDown(0) then self.dragging = false end
    -- turns slowly by itself, unless held or touched a moment ago
    if not self.dragging and now - self.touchMs > SPIN_RESUME_MS then
        self.ry = (self.ry + SPIN_DEG_PER_S * dt) % 360
    end
    if self.model then
        if not self.fitted then self.fitted = self:fit() end
        self.javaObject:fromLua1("setGizmoVisible", "none")
        self:applyView()
    end
end

function KnoxInspectScene:render()
    -- no 3D model: the icon, large
    if not self.model and self.window.item then
        local s = math.floor(math.min(self:getWidth(), self:getHeight()) * 0.7)
        ISInventoryItem.renderItemIcon(self, self.window.item, math.floor((self:getWidth() - s) / 2),
            math.floor((self:getHeight() - s) / 2), 1, s, s)
    end
    -- control hints: whole "key - action" parts per line, as many lines as
    -- the width needs, kept at the bottom
    local ft = T.fontTileH
    local maxW = self:getWidth() - 12
    if self.hintW ~= maxW then
        self.hintW = maxW
        self.hintLines = {}
        local line = ""
        local text = getText("IGUI_Knox_InspectHint")
        local parts = {}
        for part in string.gmatch(text, "[^ ]+ %- [^ ]+") do table.insert(parts, part) end
        if #parts == 0 then parts = {text} end
        for _, part in ipairs(parts) do
            local try = line == "" and part or (line .. "   " .. part)
            if line ~= "" and T.measure(T.fontTile, try) > maxW then
                table.insert(self.hintLines, line)
                line = part
            else
                line = try
            end
        end
        if line ~= "" then table.insert(self.hintLines, line) end
    end
    local n = #self.hintLines
    for i, l in ipairs(self.hintLines) do
        T.text(self, l, 6, self:getHeight() - (n - i + 1) * (ft + 2) - 2, T.color.dim, T.fontTile, 0.8)
    end
end

function KnoxInspectScene:onMouseDown(x, y)
    self.window:activate()
    local now = getTimestampMs()
    if now - (self.lastDownMs or 0) < 350 then
        self:resetView()   -- double click: back to the starting view
        self.lastDownMs = 0
        return true
    end
    self.lastDownMs = now
    self.dragging = true
    self.touchMs = now
    return true
end

-- right button held: move the view
function KnoxInspectScene:onRightMouseDown(x, y)
    self.window:activate()
    self.panning = true
    self.touchMs = getTimestampMs()
    return true
end

function KnoxInspectScene:onRightMouseUp(x, y)
    self.panning = false
    return true
end

function KnoxInspectScene:onRightMouseUpOutside(x, y)
    self.panning = false
    return true
end

local function turn(self, dx, dy)
    if self.panning then
        if not isMouseButtonDown(1) then self.panning = false return end
        self.touchMs = getTimestampMs()
        self.javaObject:fromLua2("dragView", dx, dy)
        self.panX, self.panY = (self.panX or 0) + dx, (self.panY or 0) + dy
        return
    end
    if not self.dragging then return end
    self.touchMs = getTimestampMs()
    if isKeyDown(Keyboard.KEY_LSHIFT) or isKeyDown(Keyboard.KEY_RSHIFT) then
        self.rz = (self.rz + dx * 0.5) % 360
    else
        self.ry = (self.ry + dx * 0.5) % 360
        self.rx = (self.rx + dy * 0.5) % 360
    end
end

function KnoxInspectScene:onMouseMove(dx, dy) turn(self, dx, dy) return true end
function KnoxInspectScene:onMouseMoveOutside(dx, dy) turn(self, dx, dy) return true end
function KnoxInspectScene:onMouseUp(x, y) self.dragging = false return true end
function KnoxInspectScene:onMouseUpOutside(x, y) self.dragging = false return true end

function KnoxInspectScene:onMouseWheel(del)
    self.zoom = math.max(4, math.min(30, self.zoom - del))
    self.touchMs = getTimestampMs()
    return true
end

-- Stats --------------------------------------------------------------------------

local function round(v, d)
    local m = 10 ^ (d or 0)
    return math.floor(v * m + 0.5) / m
end

local function pct(v) return round(v * 100) .. "%" end

--- Stat rows of an item: {label, value, frac (0..1 or nil), color}.
local function statsOf(item)
    local rows = {}
    local function row(key, value, frac, color)
        table.insert(rows, {label = getText("IGUI_Knox_Stat_" .. key), value = tostring(value), frac = frac, color = color})
    end
    local function condition()
        local max = item:getConditionMax()
        if max and max > 0 then
            local f = item:getCondition() / max
            row("Condition", round(f * 100) .. "%", f, f > 0.6 and T.color.good or (f > 0.25 and T.color.warn or T.color.bad))
        end
    end

    if instanceof(item, "HandWeapon") then
        local maxD = item:getMaxDamage()
        row("Damage", round(item:getMinDamage(), 1) .. " - " .. round(maxD, 1), math.min(1, maxD / 4))
        row("Range", round(item:getMaxRange(), 2), math.min(1, item:getMaxRange() / 2))
        row("Speed", round(item:getBaseSpeed(), 2), math.min(1, item:getBaseSpeed() / 1.5))
        row("Crit", round(item:getCriticalChance()) .. "%", math.min(1, item:getCriticalChance() / 100))
        if item:isRanged() and item:getMaxAmmo() > 0 then
            row("Ammo", item:getCurrentAmmoCount() .. " / " .. item:getMaxAmmo(), item:getCurrentAmmoCount() / item:getMaxAmmo())
        end
        condition()
    elseif instanceof(item, "Clothing") then
        row("Bite", round(item:getBiteDefense()) .. "%", item:getBiteDefense() / 100)
        row("Scratch", round(item:getScratchDefense()) .. "%", item:getScratchDefense() / 100)
        if item.getBulletDefense then row("Bullet", round(item:getBulletDefense()) .. "%", item:getBulletDefense() / 100) end
        row("Insulation", pct(item:getInsulation()), item:getInsulation())
        row("Wind", pct(item:getWindresistance()), item:getWindresistance())
        row("Water", pct(item:getWaterResistance()), item:getWaterResistance())
        condition()
    elseif instanceof(item, "Food") then
        local hunger = -item:getHungerChange() * 100
        if hunger ~= 0 then row("Hunger", round(hunger), math.min(1, hunger / 100), T.color.good) end
        local thirst = -item:getThirstChange() * 100
        if thirst ~= 0 then row("Thirst", round(thirst), math.min(1, thirst / 100), T.color.good) end
        if item:getCalories() ~= 0 then row("Calories", round(item:getCalories())) end
        local fresh = item:isRotten() and "Rotten" or (item:isFresh() and "Fresh" or "Stale")
        if item:getOffAgeMax() < 1000000000 then
            row("Freshness", getText("IGUI_Knox_" .. fresh), nil,
                fresh == "Rotten" and T.color.bad or (fresh == "Stale" and T.color.warn or T.color.good))
        end
    elseif instanceof(item, "InventoryContainer") and item:getInventory() then
        local inv = item:getInventory()
        local cap = inv:getCapacity()
        row("Capacity", round(cap, 1))
        row("Filled", round(inv:getCapacityWeight(), 1) .. " / " .. round(cap, 1), cap > 0 and math.min(1, inv:getCapacityWeight() / cap) or nil)
        if item:getWeightReduction() > 0 then row("Reduction", item:getWeightReduction() .. "%", item:getWeightReduction() / 100) end
    else
        condition()
    end
    if item:IsDrainable() then
        row("Left", pct(item:getCurrentUsesFloat()), item:getCurrentUsesFloat())
    end
    local fluid = item:getFluidContainer()
    if fluid and fluid:getCapacity() > 0 then
        row("Fluid", round(fluid:getAmount(), 2) .. " / " .. round(fluid:getCapacity(), 2) .. " " .. getText("IGUI_Knox_LitersShort"),
            fluid:getAmount() / fluid:getCapacity(), T.color.liquid)
    end
    local w, h = KnoxFootprint.get(item)
    row("Weight", round(KnoxGrid.weightOf(item), 2) .. " " .. getText("IGUI_Knox_Kg"))
    row("Size", w .. "x" .. h)
    return rows
end

local function descriptionOf(item)
    local key = item.getTooltip and item:getTooltip()
    if key and key ~= "" then
        local text = getTextOrNull(key)
        if text and text ~= "" then return text end
    end
    return nil
end

-- Window -----------------------------------------------------------------------------

KnoxInspectWindow = ISPanel:derive("KnoxInspectWindow")
KnoxInspectWindow.list = {}

--- Is this item being inspected? (its tile or slot gets a sand frame)
function KnoxInspectWindow.isOpen(item)
    for _, w in ipairs(KnoxInspectWindow.list) do
        if w.item == item then return w end
    end
    return nil
end

function KnoxInspectWindow:new(host, item, playerNum)
    local o = ISPanel:new(0, 0, 10, 10)
    setmetatable(o, self)
    self.__index = self
    o.host = host
    o.item = item
    o.playerNum = playerNum
    o.background = false
    o.moveWithMouse = false
    return o
end

function KnoxInspectWindow:createChildren()
    local ft = T.fontH(T.fontText)
    local fh = T.fontH(T.fontHeader)
    local pad = T.pad
    local w = T.cell * 9
    self.headerH = T.sectionH + 4
    self.sceneH = math.floor(w * 0.55)

    self.scene = KnoxInspectScene:new(pad, self.headerH + pad, w - pad * 2, self.sceneH, self)
    self.scene:initialise()
    self.scene:instantiate()
    self:addChild(self.scene)
    self.scene:setup(self.item)

    -- text below the model
    self.rows = statsOf(self.item)
    self.rowH = ft + 6
    local desc = descriptionOf(self.item)
    self.descLines = desc and T.wrap(desc, T.fontText, w - pad * 2) or {}
    self.infoY = self.headerH + pad + self.sceneH + pad
    local h = self.infoY + fh + ft + pad + #self.rows * self.rowH
    if #self.descLines > 0 then h = h + pad + #self.descLines * ft end
    self:setWidth(w)
    self:setHeight(h + pad)
end

function KnoxInspectWindow:activate()
    KnoxInspectWindow.active = self
    self.raise = true
end

function KnoxInspectWindow:closeRect()
    local s = self.headerH - 8
    return self:getWidth() - s - 4, 4, s, s
end

function KnoxInspectWindow:prerender()
    local w, h = self:getWidth(), self:getHeight()
    local ft = T.fontH(T.fontText)
    local fh = T.fontH(T.fontHeader)
    local pad = T.pad
    local item = self.item

    -- thread from the item's tile or slot to this window
    local sx, sy, sw, sh = KnoxThread.sourceRect(item)
    -- just opened: it unfolds out of that tile or slot
    if T.unfold(self, sx, sy, sw, sh) then return end
    KnoxThread.draw(self, sx, sy, sw, sh, self.headerH, KnoxInspectWindow.active == self)

    self:drawRect(4, 6, w, h, 0.45, 0, 0, 0)
    T.rect(self, 0, 0, w, h, T.color.window)
    T.rect(self, 0, 0, w, self.headerH, T.color.header)
    T.rect(self, 0, self.headerH, w, 1, T.color.border)
    T.border(self, 0, 0, w, h, T.color.hoverEdge)
    if KnoxInspectWindow.active == self then
        local ac = T.color.accent
        local a = self.knoxMove and 1 or 0.5
        self:drawRectBorder(0, 0, w, h, a, ac.r, ac.g, ac.b)
        self:drawRectBorder(1, 1, w - 2, h - 2, a, ac.r, ac.g, ac.b)
    end

    -- header
    local cx, cy, cw, ch = self:closeRect()
    T.caps(self, getText("IGUI_Knox_InspectTitle"), 8, math.floor((self.headerH - T.fontH(T.fontCaps)) / 2), T.color.dim)
    T.closeButton(self, cx, cy, cw, self:isMouseOver() and T.inRect(self:getMouseX(), self:getMouseY(), {cx, cy, cw, ch}))

    -- model backdrop, tinted by category
    local sx, sy, sw, sh = pad, self.headerH + pad, w - pad * 2, self.sceneH
    T.rect(self, sx, sy, sw, sh, T.color.cell)
    T.rect(self, sx, sy, sw, sh, T.category[T.categoryOf(item)], 0.35)
    T.border(self, sx, sy, sw, sh, T.color.border)

    -- name and category
    local y = self.infoY
    T.text(self, T.fit(item:getDisplayName(), T.fontHeader, w - pad * 2), pad, y, T.color.bright, T.fontHeader)
    y = y + fh
    local cat = item:getDisplayCategory() or ""
    local catName = getTextOrNull("IGUI_ItemCat_" .. cat) or cat
    T.text(self, catName, pad, y, T.color.dim, T.fontText)
    y = y + ft + pad

    -- stats: label, bar, value
    local labelW = math.floor((w - pad * 2) * 0.36)
    local valueW = math.floor((w - pad * 2) * 0.26)
    local barX = pad + labelW
    local barW = w - pad * 2 - labelW - valueW - 8
    for _, r in ipairs(self.rows) do
        T.text(self, T.fit(r.label, T.fontText, labelW - 6), pad, y, T.color.dim, T.fontText)
        if r.frac then
            local bc = r.color or T.color.accent
            local by = y + math.floor(ft / 2) - 1
            T.rect(self, barX, by, barW, 3, T.color.line)
            T.rect(self, barX, by, math.floor(barW * math.max(0, math.min(1, r.frac))), 3, bc)
        end
        T.textRight(self, r.value, w - pad, y, r.color or T.color.bright, T.fontText)
        self:drawRect(pad, y + self.rowH - 3, w - pad * 2, 1, 1, T.color.line.r, T.color.line.g, T.color.line.b)
        y = y + self.rowH
    end

    -- description
    if #self.descLines > 0 then
        y = y + pad
        for _, line in ipairs(self.descLines) do
            T.text(self, line, pad, y, T.color.text, T.fontText)
            y = y + ft
        end
    end
end

function KnoxInspectWindow:onMouseDown(x, y)
    if self.foldMs then return true end
    local cx, cy, cw, ch = self:closeRect()
    if x >= cx and x < cx + cw and y >= cy and y < cy + ch then
        self:close()
        return true
    end
    self:activate()
    KnoxWindowDrag.begin(self, x, y, self.headerH)
    return true
end

KnoxWindowDrag.install(KnoxInspectWindow)

function KnoxInspectWindow:onMouseWheel(del) return true end
function KnoxInspectWindow:onRightMouseUp(x, y) return true end

function KnoxInspectWindow:close()
    for i, w in ipairs(KnoxInspectWindow.list) do
        if w == self then table.remove(KnoxInspectWindow.list, i) break end
    end
    if KnoxInspectWindow.active == self then KnoxInspectWindow.active = nil end
    if self.scene then knoxSceneTintClear(self.scene.javaObject) end
    T.fold(self, function(w)
        w:setVisible(false)
        w.host:removeChild(w)
    end)
end

--- Called by the screen before it draws its children: closes windows whose
--- item is gone (eaten, used up, destroyed), brings a clicked window to the front.
function KnoxInspectWindow.updateAll()
    local copy = {}
    for _, w in ipairs(KnoxInspectWindow.list) do table.insert(copy, w) end
    for _, w in ipairs(copy) do
        if not w.item:getContainer() and not w.item:getWorldItem() then w:close() end
    end
    for _, w in ipairs(KnoxInspectWindow.list) do
        if w.raise then
            w.raise = false
            w.host:removeChild(w)
            w.host:addChild(w)
        end
    end
end

function KnoxInspectWindow.closeAll()
    local copy = {}
    for _, w in ipairs(KnoxInspectWindow.list) do table.insert(copy, w) end
    for _, w in ipairs(copy) do w:close() end
end

--- Inspect an item (brings its window to the front if already open).
function KnoxInspectWindow.open(item, playerNum)
    local host = KnoxScreen and KnoxScreen.instance
    if not host then return end
    for _, w in ipairs(KnoxInspectWindow.list) do
        if w.item == item then w:activate() return end
    end
    local w = KnoxInspectWindow:new(host, item, playerNum)
    w:initialise()
    w:instantiate()
    local n = #KnoxInspectWindow.list
    w:setX(math.floor((host:getWidth() - w:getWidth()) / 2) + n * 24)
    w:setY(math.max(8, math.floor((host:getHeight() - w:getHeight()) / 2)) + n * 24)
    host:addChild(w)
    w.openedMs = getTimestampMs()
    table.insert(KnoxInspectWindow.list, w)
    KnoxInspectWindow.active = w
end

-- "Inspect" on top of every item context menu (opens the Knox screen first
-- when it is closed, e.g. a menu from the world).
local function onFillMenu(playerNum, context, items)
    if Knox and Knox.forPlayer and not Knox.forPlayer(playerNum) then return end   -- the game's windows for them
    local first = items and items[1]
    if not first then return end
    local item = instanceof(first, "InventoryItem") and first or (first.items and first.items[1])
    if not item then return end
    context:addOptionOnTop(getText("IGUI_Knox_Inspect"), item, function(it)
        -- (guarded as the inventory key: a screen failing to open gives the game's inventory back)
